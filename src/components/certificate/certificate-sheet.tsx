"use client"

/**
 * ============================================================================
 * CertificateSheet — the only thing in the product that draws a certificate
 * ============================================================================
 *
 * CERT-CONS-001 §5.1, §10. It renders the SVG the backend generates, which is
 * the same document the PDF is built from — so the preview and the download
 * cannot disagree (AC-04).
 *
 * ── Why the sheet used to be cropped ────────────────────────────────────────
 *
 * The previous implementation laid the certificate out as absolutely
 * positioned HTML on a fixed 1489 × 1053 pixel canvas and scaled it with
 *
 *     transform: scale(calc(100cqw / 1489))
 *
 * `calc(100cqw / 1489)` divides a length by a number and therefore *is* a
 * length; `scale()` accepts `<number> | <percentage>`. The value is invalid, so
 * the whole declaration was dropped — and with no fallback the canvas rendered
 * at its natural 1489 × 1053 inside a viewport with `overflow: hidden`. The
 * learner saw the top-left 31% of the sheet (C-01).
 *
 * The whole responsive strategy is now these three properties:
 *
 *     viewBox="0 0 1489 1053"   width: 100%   height: auto
 *
 * which is correct in every browser, at every size, in a dialog, on a phone and
 * in print. There is no container query, no transform and no arithmetic left to
 * get wrong.
 */

import { useMemo } from "react"
import { AlertCircle, RefreshCw } from "lucide-react"
import { Button } from "@/components/ui/button"
import { Skeleton } from "@/components/ui/skeleton"
import { cn } from "@/lib/utils"
import { useCertificateDocument, describeCertificateError } from "./use-certificate"

/** The canonical aspect ratio: A4 landscape, 1489 / 1053 = 1.41406. */
export const CERTIFICATE_ASPECT_RATIO = 1489 / 1053

export interface CertificateSheetProps {
  certificateId: string
  /** Accessible name; falls back to a generic label. */
  label?: string
  className?: string
  /** Rendered instead of the skeleton while the document loads. */
  fallback?: React.ReactNode
}

/**
 * Strips the outer `<svg>` wrapper so the markup can be injected into an
 * `<svg>` this component controls — which is what keeps `width`/`height`
 * ours rather than the document's, and lets React own the accessibility
 * attributes.
 *
 * The document is generated by our own backend from a fixed template with every
 * interpolated value XML-escaped: it contains no `<script>`, no
 * `<foreignObject>` and no external reference by construction. The `<script>`
 * strip below is belt-and-braces against a future change to the generator, not
 * a defence against the current one.
 */
function innerMarkup(svg: string): string {
  return svg
    .replace(/^[\s\S]*?<svg[^>]*>/i, "")
    .replace(/<\/svg>\s*$/i, "")
    .replace(/<script[\s\S]*?<\/script>/gi, "")
    .replace(/<foreignObject[\s\S]*?<\/foreignObject>/gi, "")
}

export function CertificateSheet({
  certificateId,
  label,
  className,
  fallback,
}: CertificateSheetProps) {
  const { svg, isLoading, error, refresh } = useCertificateDocument(certificateId)

  const inner = useMemo(() => (svg ? innerMarkup(svg) : null), [svg])

  if (isLoading) {
    return (
      <div className={cn("w-full", className)}>
        {fallback ?? (
          <Skeleton
            className="w-full rounded-md"
            style={{ aspectRatio: `${1489} / ${1053}` }}
          />
        )}
      </div>
    )
  }

  if (error || !inner) {
    return (
      <div
        className={cn(
          "flex w-full flex-col items-center justify-center gap-3 rounded-md border border-border bg-muted/30 p-8 text-center",
          className
        )}
        style={{ aspectRatio: `${1489} / ${1053}` }}
      >
        <AlertCircle className="h-6 w-6 text-muted-foreground" />
        <div>
          <p className="text-sm font-medium text-foreground">
            We couldn&apos;t load your certificate
          </p>
          <p className="mt-1 text-sm text-muted-foreground">
            {error ? describeCertificateError(error) : "The document was empty."}
          </p>
        </div>
        <Button variant="outline" size="sm" onClick={() => void refresh()} className="gap-2">
          <RefreshCw className="h-3.5 w-3.5" />
          Try again
        </Button>
      </div>
    )
  }

  return (
    <div
      className={cn(
        // A hairline and a soft shadow so the white sheet reads as a document
        // against a white page rather than dissolving into it.
        "w-full overflow-hidden rounded-md border border-border/70 bg-white shadow-sm",
        className
      )}
      data-certificate-sheet
    >
      <svg
        viewBox="0 0 1489 1053"
        role="img"
        aria-label={label ?? "Certificate of completion"}
        style={{ width: "100%", height: "auto", display: "block" }}
        dangerouslySetInnerHTML={{ __html: inner }}
      />
    </div>
  )
}
